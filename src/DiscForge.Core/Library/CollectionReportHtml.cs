using System.Net;
using System.Text;

namespace DiscForge.Core.Library;

/// <summary>
/// Renders a <see cref="LibraryReport"/> as a self-contained HTML dashboard — a
/// shareable, reopenable view of a collection's health: how much is verified, mis-named,
/// duplicated or unrecognised, and what's still missing from the set. All CSS is inlined
/// so the file stands alone. Presentation only; it reports what the scan found.
/// </summary>
public static class CollectionReportHtml
{
    public static string Build(LibraryReport report, string? title = null)
    {
        ArgumentNullException.ThrowIfNull(report);
        string heading = title ?? (report.DatName is not null ? $"Collection vs {report.DatName}" : "Collection report");

        var sb = new StringBuilder();
        sb.Append("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\">");
        sb.Append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">");
        sb.Append("<title>").Append(E(heading)).Append("</title><style>");
        sb.Append(Css());
        sb.Append("</style></head><body>");

        sb.Append("<h1>").Append(E(heading)).Append("</h1>");
        sb.Append("<p class=\"sub\">Root: <code>").Append(E(report.Root)).Append("</code>");
        if (report.DatName is not null) sb.Append(" &#183; DAT: ").Append(E(report.DatName));
        sb.Append("</p>");

        // Summary cards.
        sb.Append("<div class=\"cards\">");
        Card(sb, "Total", report.Total, "");
        Card(sb, "Verified", report.Verified, "ok");
        Card(sb, "Misnamed", report.Misnamed, "warn");
        Card(sb, "Duplicates", report.Duplicates, "warn");
        Card(sb, "Unknown", report.Unknown, "bad");
        Card(sb, "Missing", report.Missing.Count, report.Missing.Count > 0 ? "bad" : "ok");
        sb.Append("</div>");

        // Files table.
        sb.Append("<h2>Files</h2><table><thead><tr><th>Status</th><th>File</th><th>Game</th><th>Suggested name</th></tr></thead><tbody>");
        foreach (var e in report.Entries)
        {
            string cls = e.Status switch
            {
                LibraryStatus.Verified => "ok",
                LibraryStatus.Misnamed or LibraryStatus.Duplicate => "warn",
                _ => "bad",
            };
            sb.Append("<tr><td><span class=\"tag ").Append(cls).Append("\">")
              .Append(E(e.Status.ToString())).Append("</span></td><td>")
              .Append(E(e.FileName)).Append("</td><td>")
              .Append(E(e.Match?.Game ?? (e.RomPlatform.Length > 0 ? e.RomPlatform : e.Format)))
              .Append("</td><td>").Append(E(e.SuggestedName ?? "")).Append("</td></tr>");
        }
        sb.Append("</tbody></table>");

        // Missing list.
        if (report.Missing.Count > 0)
        {
            sb.Append("<h2>Missing from set (").Append(report.Missing.Count).Append(")</h2><ul class=\"missing\">");
            foreach (var m in report.Missing) sb.Append("<li>").Append(E(m.Name)).Append("</li>");
            sb.Append("</ul>");
        }

        sb.Append("<p class=\"foot\">Generated by DiscForge.</p></body></html>");
        return sb.ToString();
    }

    private static void Card(StringBuilder sb, string label, int value, string cls)
    {
        sb.Append("<div class=\"card ").Append(cls).Append("\"><div class=\"n\">")
          .Append(value.ToString("N0")).Append("</div><div class=\"l\">").Append(E(label)).Append("</div></div>");
    }

    private static string Css() =>
        "body{font-family:system-ui,Segoe UI,Arial,sans-serif;margin:24px;color:#1b1b1b;background:#fafafa}" +
        "h1{margin:0 0 4px}h2{margin-top:28px}.sub{color:#666;margin-top:0}code{background:#eee;padding:1px 4px;border-radius:3px}" +
        ".cards{display:flex;flex-wrap:wrap;gap:12px;margin:16px 0}" +
        ".card{background:#fff;border:1px solid #e2e2e2;border-radius:8px;padding:12px 18px;min-width:96px;text-align:center}" +
        ".card .n{font-size:26px;font-weight:700}.card .l{color:#666;font-size:13px}" +
        ".card.ok .n{color:#1c7c34}.card.warn .n{color:#b26a00}.card.bad .n{color:#b02020}" +
        "table{border-collapse:collapse;width:100%;background:#fff;border:1px solid #e2e2e2}" +
        "th,td{padding:6px 10px;text-align:left;border-bottom:1px solid #eee;font-size:14px}th{background:#f0f0f0}" +
        ".tag{padding:1px 8px;border-radius:10px;font-size:12px;color:#fff}.tag.ok{background:#1c7c34}.tag.warn{background:#b26a00}.tag.bad{background:#b02020}" +
        ".missing{columns:2;color:#444}.foot{color:#999;margin-top:24px;font-size:12px}";

    private static string E(string s) => WebUtility.HtmlEncode(s);
}
